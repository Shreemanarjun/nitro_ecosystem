// Native-assets build-hook linking (perf lever 1 / v0.8.0). When a plugin opts
// into the native-assets path (`nitrogen generate --native-assets`), the
// generated Dart resolves C symbols via top-level `@Native` externals against a
// code asset built by `hook/build.dart` — instead of DynamicLibrary at runtime.
// This step writes that hook, vendors nitro's C runtime next to it, and adds
// the build-time hook dependencies to the plugin's pubspec.

/// Writes `hook/build.dart`, vendors nitro's C sources/headers into
/// `src/nitro_native/`, and injects the hook deps into `pubspec.yaml` for the
/// all-C++ modules in [moduleInfos].
///
/// Returns true only if it actually wrote the hook. It REFUSES (returns false,
/// touches nothing) when the native-assets path is unsafe/inapplicable, so a
/// plugin with its own native build (e.g. nitro_server's cmake engine) is never
/// clobbered and the caller can fall back to the standard CMake/podspec link:
///   • an existing hand-written `hook/build.dart` (not nitrogen-generated), or
///   • any generated `*.g.dart` still on the DynamicLibrary (`_dylib`) path,
///     i.e. a module fell back (TypedData / @zeroCopy / Stream-of-imported-
///     struct / mixed Swift-Kotlin) so a CBuilder hook would mismatch it.
bool linkNativeAssetsHook(
  List<ModuleInfo> moduleInfos,
  String nitroNativePath, {
  String baseDir = '.',
}) {
  final cppModules = moduleInfos.where((m) => m.isCpp).toList();
  if (cppModules.isEmpty) return false;

  // ── Safety gate (a): never overwrite the plugin's own native build ────────
  final hookFile = File(p.join(baseDir, 'hook', 'build.dart'));
  if (hookFile.existsSync() && !hookFile.readAsStringSync().contains('GENERATED BY nitrogen')) {
    stdout.writeln(
      "  native-assets: SKIPPED — hook/build.dart is hand-written (not nitrogen-generated), "
      "so this plugin has its own native build; refusing to overwrite it. "
      "Delete the hook first if you really want the generated native-assets hook.",
    );
    return false;
  }

  // ── Safety gate (b): every module must actually be on the @Native path ────
  // The emit is opt-in per the native_assets build option; an ineligible module
  // (TypedData/@zeroCopy/Stream-of-imported-struct, or a Swift/Kotlin module)
  // falls back to the _dylib path, which a CBuilder hook can't satisfy.
  final fellBack = <String>[];
  final libDir = Directory(p.join(baseDir, 'lib'));
  if (libDir.existsSync()) {
    for (final f in libDir.listSync(recursive: true).whereType<File>()) {
      if (f.path.endsWith('.g.dart') && f.readAsStringSync().contains('_dylib')) {
        fellBack.add(p.relative(f.path, from: baseDir));
      }
    }
  }
  if (fellBack.isNotEmpty) {
    stdout.writeln(
      "  native-assets: SKIPPED — not all modules use the @Native path (${fellBack.join(', ')} "
      "still resolve via DynamicLibrary: likely TypedData/@zeroCopy/Stream or a Swift/Kotlin "
      "module). The native-assets hook only supports fully-eligible, self-contained all-C++ "
      "modules; leaving the standard CMake/podspec build in place.",
    );
    return false;
  }

  // ── External-build mode: the plugin has its own cmake project (src/
  // CMakeLists.txt — an engine + external deps). Drive THAT build and declare
  // the produced library as the code asset, instead of CBuilder compiling a
  // fixed source list. The generated Dart is already @Native (gates passed);
  // @Native is build-agnostic (binds by assetId + symbols), so it resolves the
  // cmake-built library the same as a CBuilder one.
  if (File(p.join(baseDir, 'src', 'CMakeLists.txt')).existsSync()) {
    if (cppModules.length != 1) {
      stdout.writeln(
        "  native-assets: SKIPPED — external cmake build currently supports a single C++ "
        "module (found ${cppModules.map((m) => m.lib).join(', ')}); using standard linking.",
      );
      return false;
    }
    final mod = cppModules.single;
    final libStem = mod.lib.replaceAll('-', '_');
    final pkg = _readPubspecName(baseDir) ?? libStem;
    Directory(p.join(baseDir, 'hook')).createSync(recursive: true);
    File(p.join(baseDir, 'hook', 'build.dart'))
        .writeAsStringSync(buildExternalCmakeHookDart(libStem: libStem, pkg: pkg));
    // The external cmake hook imports ONLY hooks + code_assets (it drives cmake
    // via Process.run — no CBuilder). Do NOT inject native_toolchain_c: it
    // pins hooks ^2.x and would conflict with a plugin on hooks ^1.x.
    injectNativeAssetsPubspecDeps(
      p.join(baseDir, 'pubspec.yaml'),
      deps: {'hooks': nativeAssetsHookDeps['hooks']!, 'code_assets': nativeAssetsHookDeps['code_assets']!},
    );
    stdout.writeln('  native-assets: wrote hook/build.dart (external cmake build → code asset: $libStem)');
    _warnDoubleBundle([libStem], baseDir);
    return true;
  }

  // 1. Vendor nitro's C sources + headers next to the hook so CBuilder finds
  //    them package-relative (mirrors how linkCMake copies nitro.h into include
  //    dirs). Portable: no machine-specific absolute path baked into the hook.
  //    Shared by every module's asset.
  final vendorDir = Directory(p.join(baseDir, 'src', 'nitro_native'))..createSync(recursive: true);
  final nitroNative = Directory(nitroNativePath);
  for (final name in [...nativeAssetsVendoredCSources, ...nativeAssetsVendoredHeaders]) {
    final src = File(p.join(nitroNative.path, name));
    if (src.existsSync()) src.copySync(p.join(vendorDir.path, name));
  }
  final internalSrc = Directory(p.join(nitroNative.path, 'internal'));
  if (internalSrc.existsSync()) {
    final internalDst = Directory(p.join(vendorDir.path, 'internal'))..createSync(recursive: true);
    for (final f in internalSrc.listSync().whereType<File>()) {
      f.copySync(p.join(internalDst.path, p.basename(f.path)));
    }
  }

  // 2. One code asset per C++ module. The impl path is included UNCONDITIONALLY
  //    (the user's impl, same convention as CMake's target_sources) — it may not
  //    exist yet at link time (chicken-and-egg: hook is written during generate,
  //    impl written after). The generated <lib>.impl.g.cpp starter guides the
  //    user; the build errors clearly if src/HybridXxx.cpp is absent.
  final modules = [
    for (final mod in cppModules)
      (
        libStem: mod.lib.replaceAll('-', '_'),
        cppSources: <String>[
          'lib/src/generated/cpp/${mod.lib}.bridge.g.cpp',
          // Impl filename follows the lib stem (Hybrid<PascalCase(lib)>.cpp) —
          // the SAME convention as linkCMake (cmake.dart: className from m.lib),
          // NOT the module class name (e.g. lib `nitro_server` -> module class
          // `NitroServerNative` but impl file `HybridNitroServer.cpp`).
          'src/Hybrid${_toPascalCase(mod.lib)}.cpp',
        ],
      ),
  ];

  // 3. hook/build.dart (one CBuilder.library per module)
  Directory(p.join(baseDir, 'hook')).createSync(recursive: true);
  File(p.join(baseDir, 'hook', 'build.dart')).writeAsStringSync(buildHookDart(modules: modules));

  // 4. pubspec hook deps (regular dependencies — consumers run the hook).
  injectNativeAssetsPubspecDeps(p.join(baseDir, 'pubspec.yaml'));

  stdout.writeln('  native-assets: wrote hook/build.dart + vendored nitro C runtime '
      '(asset${modules.length == 1 ? '' : 's'}: ${modules.map((m) => m.libStem).join(', ')})');
  _warnDoubleBundle([for (final m in modules) m.libStem], baseDir);
  return true;
}

/// Warns that a code-asset hook + a platform native build double-bundle the
/// engine (two C++ runtimes → split-brain abort). Warn-only, not a neutralizer.
void _warnDoubleBundle(List<String> libStems, String baseDir) {
  final pubspecFile = File(p.join(baseDir, 'pubspec.yaml'));
  final plats = pubspecFile.existsSync()
      ? nativeBuildPlatforms(pubspecFile.readAsStringSync())
      : const <String>[];
  final remedy = plats.isEmpty
      ? "remove any platform native engine build (drop `ffiPlugin: true` and/or the "
          "pluginClass native sources) for the covered platforms"
      : "remove the native engine build under `flutter.plugin.platforms` for: "
          "${plats.join(', ')} (drop `ffiPlugin: true` and/or `pluginClass:` + its "
          "native sources there)";
  stdout.writeln(
    "  native-assets: WARNING — this plugin ALSO builds its native code via its "
    "platform projects (ffiPlugin / podspec / gradle / CMakeLists), so under "
    "`flutter build` that engine AND this code asset (${libStems.join(', ')}) are "
    "BOTH bundled → two copies of the C++ runtime → split-brain global state "
    "(instance registry, completion batch) → double-free/abort at runtime. To adopt "
    "native-assets, $remedy so ONLY the hook bundles the library.",
  );
}

/// Platforms under `flutter.plugin.platforms` that build the engine themselves
/// (`ffiPlugin: true` or a `pluginClass:`) — the ones that double-bundle with a
/// code asset. Ignores comment lines; `web` has no native build.
List<String> nativeBuildPlatforms(String pubspecContent) {
  final out = <String>[];
  for (final plat in const ['android', 'ios', 'macos', 'windows', 'linux']) {
    final block = _pubspecBlock(pubspecContent, plat);
    if (block == null) continue;
    final live = block.split('\n').where((l) => !l.trimLeft().startsWith('#')).join('\n');
    if (RegExp(r'ffiPlugin:\s*true').hasMatch(live) || RegExp(r'pluginClass:\s*\S').hasMatch(live)) {
      out.add(plat);
    }
  }
  return out;
}

/// True if `<baseDir>/hook/build.dart` exists and is nitrogen-generated (carries
/// the "GENERATED BY nitrogen" sentinel) — i.e. a native-assets code-asset hook.
bool hasGeneratedNativeAssetsHook(String baseDir) {
  final f = File(p.join(baseDir, 'hook', 'build.dart'));
  return f.existsSync() && f.readAsStringSync().contains('GENERATED BY nitrogen');
}

/// True if `hook/build.dart` declares a `CodeAsset` — generated OR hand-written
/// (e.g. nitro_server's prebuilt downloader). Such a hook delivers the library,
/// so a platform that also builds the engine double-bundles.
bool hookDeclaresCodeAsset(String baseDir) {
  final f = File(p.join(baseDir, 'hook', 'build.dart'));
  if (!f.existsSync()) return false;
  final s = f.readAsStringSync();
  return s.contains('CodeAsset(') || s.contains('assets.code.add');
}

/// Removes a stale generated hook (+ vendored runtime) when the plugin is no
/// longer on the native-assets path, so it can't double-bundle with the `_dylib`
/// build. Sentinel-gated (never touches a hand-written hook). Returns the
/// removed paths, relative to [baseDir].
List<String> removeStaleNativeAssetsHook(String baseDir) {
  final removed = <String>[];
  if (!hasGeneratedNativeAssetsHook(baseDir)) return removed;
  File(p.join(baseDir, 'hook', 'build.dart')).deleteSync();
  removed.add(p.join('hook', 'build.dart'));
  final hookDir = Directory(p.join(baseDir, 'hook'));
  if (hookDir.existsSync() && hookDir.listSync().isEmpty) hookDir.deleteSync();
  final vendored = Directory(p.join(baseDir, 'src', 'nitro_native'));
  if (vendored.existsSync()) {
    vendored.deleteSync(recursive: true);
    removed.add(p.join('src', 'nitro_native'));
  }
  return removed;
}

/// The `<key>:` flow-map line, or the block header plus only its more-indented
/// children (mirrors the doctor's `_yamlBlock`; a sibling key is excluded).
String? _pubspecBlock(String yaml, String key) {
  final lines = yaml.split('\n');
  for (var i = 0; i < lines.length; i++) {
    if (RegExp('^\\s*$key:\\s*\\{.*\\}').hasMatch(lines[i])) return lines[i]; // flow map
    final m = RegExp('^(\\s*)$key:\\s*\$').firstMatch(lines[i]);
    if (m == null) continue;
    final indent = m.group(1)!.length;
    final out = [lines[i]];
    for (var j = i + 1; j < lines.length; j++) {
      final l = lines[j];
      if (l.trim().isEmpty || l.trimLeft().startsWith('#')) continue;
      if (l.length - l.trimLeft().length <= indent) break;
      out.add(l);
    }
    return out.join('\n');
  }
  return null;
}

/// Reads the top-level `name:` from `<baseDir>/pubspec.yaml` (the pub package,
/// which the @Native assetId uses as `package:<name>/<libStem>`). Null if absent.
String? _readPubspecName(String baseDir) {
  final f = File(p.join(baseDir, 'pubspec.yaml'));
  if (!f.existsSync()) return null;
  final m = RegExp(r'^name:\s*([A-Za-z_][A-Za-z0-9_]*)', multiLine: true).firstMatch(f.readAsStringSync());
  return m?.group(1);
}

/// Adds any missing [deps] (default [nativeAssetsHookDeps]) under the
/// `dependencies:` block of the pubspec at [pubspecPath]. Returns true if the
/// file was changed. The external-cmake hook passes only {hooks, code_assets}
/// (it has no CBuilder, so native_toolchain_c — which pins hooks ^2.x — must
/// not be forced onto a hooks ^1.x plugin).
bool injectNativeAssetsPubspecDeps(String pubspecPath, {Map<String, String>? deps}) {
  final f = File(pubspecPath);
  if (!f.existsSync()) return false;
  var content = f.readAsStringSync();
  final missing = (deps ?? nativeAssetsHookDeps).entries
      .where((e) => !RegExp('^  ${e.key}:', multiLine: true).hasMatch(content))
      .toList();
  if (missing.isEmpty) return false;
  final depsMatch = RegExp(r'^dependencies:[ \t]*$', multiLine: true).firstMatch(content);
  if (depsMatch == null) return false;
  final insert = '\n${missing.map((e) => '  ${e.key}: ${e.value}').join('\n')}';
  content = content.replaceRange(depsMatch.end, depsMatch.end, insert);
  f.writeAsStringSync(content);
  return true;
}
