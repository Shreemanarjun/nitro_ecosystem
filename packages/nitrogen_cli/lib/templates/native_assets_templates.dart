// Native-assets build-hook templates (perf lever 1 / v0.8.0 migration).
//
// Emits a `hook/build.dart` that compiles a Nitro plugin's C++ bridge + impl
// (+ the vendored Dart DL API) into a Dart **code asset** via
// `native_toolchain_c`'s `CBuilder`. The asset is resolved at runtime by the
// generated `@Native external` bindings (no `DynamicLibrary.open`/`process`),
// which is what lets `@Native` work on Android (the `RTLD_LOCAL` symbol-
// visibility wall that blocks `lookupFunction` there).
//
// CBuilder cross-compiles per target automatically: macOS/iOS via xcrun, Android
// via the NDK, Linux via clang, Windows via cl — one hook, every platform.
//
// Opt-in: only generated for all-C++ Nitro modules that enable the native-assets
// path (`nitrogen generate --native-assets`). Swift/Kotlin impl modules keep
// their Xcode/Gradle linking.
library;

/// The hook's `dependencies` the consuming plugin must declare (build-time).
/// They live in regular `dependencies` (NOT dev_dependencies) so that packages
/// depending on this plugin resolve them when running the build hook.
const nativeAssetsHookDeps = {
  'hooks': '^2.2.0',
  'code_assets': '^2.1.0',
  'native_toolchain_c': '^0.19.5',
  'logging': '^1.2.0',
};

/// nitro C-runtime sources the hook compiles alongside the bridge (vendored
/// into the plugin's `src/nitro_native/` at link time — the DL API provides
/// `Dart_InitializeApiDL` / `Dart_PostCObject_DL` the async/stream paths need).
const nativeAssetsVendoredCSources = ['dart_api_dl.c'];

/// Headers vendored next to [nativeAssetsVendoredCSources] so the bridge +
/// dart_api_dl.c compile (header-only nitro runtime + the Dart API headers).
const nativeAssetsVendoredHeaders = [
  'dart_api_dl.h',
  'dart_api.h',
  'dart_native_api.h',
  'dart_version.h',
  'nitro.h',
  'nitro_completion_batch.h',
  'nitro_worker_pool.h',
  'nitro_background.h',
];

/// One C++ module → one code asset. `libStem` is the sanitized module name
/// (asset id `package:$pkg/$libStem`, matching the generated `@Native`
/// bindings); `cppSources` are the generated bridge + the impl.
typedef NativeAssetsModule = ({String libStem, List<String> cppSources});

/// Contents of `hook/build.dart` — one `CBuilder.library` per [modules] entry
/// (multi-module plugins build one code asset each; each module's generated
/// Dart resolves against its own asset). The vendored Dart DL API in
/// [vendoredDir] is compiled into every asset.
String buildHookDart({
  required List<NativeAssetsModule> modules,
  String vendoredDir = 'src/nitro_native',
}) {
  String builder(NativeAssetsModule m) {
    final sources = [
      ...m.cppSources,
      for (final c in nativeAssetsVendoredCSources) '$vendoredDir/$c',
    ].map((s) => "        '$s',").join('\n');
    return '''    await CBuilder.library(
      name: '${m.libStem}',
      assetName: '${m.libStem}',
      language: Language.cpp,
      sources: [
$sources
      ],
      // vendored nitro C runtime + the generated-cpp dir (the impl #includes
      // <lib>.native.g.h, which lives beside the generated bridge).
      includes: ['$vendoredDir', 'lib/src/generated/cpp'],
      std: 'c++17',
      cppLinkStdLib: android ? 'c++_static' : null,
    ).run(input: input, output: output, logger: logger);''';
  }

  final builders = modules.map(builder).join('\n');
  return '''
// GENERATED BY nitrogen — native-assets build hook (do not edit).
import 'dart:io';

import 'package:code_assets/code_assets.dart';
import 'package:hooks/hooks.dart';
import 'package:logging/logging.dart';
import 'package:native_toolchain_c/native_toolchain_c.dart';

// Compiles each Nitro C++ bridge + impl (+ vendored Dart DL API) into its own
// code asset. CBuilder cross-compiles for whichever target the SDK/Flutter
// requests (xcrun / NDK / clang / cl); the generated `@Native` bindings resolve
// against these assets.
void main(List<String> args) async {
  await build(args, (input, output) async {
    // Android's NDK defaults to the SHARED libc++ (libc++_shared.so), which a
    // bare code asset doesn't bundle → dlopen fails. Link it statically so the
    // .so is self-contained. Apple/Linux keep their system default.
    final android = input.config.code.targetOS == OS.android;
    // Root logger ('') — setting .level on a NAMED logger throws unless
    // hierarchicalLoggingEnabled is set, so use the root here.
    final logger = Logger('')
      ..level = Level.SEVERE
      ..onRecord.listen((r) => stderr.writeln('\${r.level.name}: \${r.message}'));
$builders
  });
}
''';
}

/// `hook/build.dart` for a plugin with its own cmake project ([cmakeSrcDir]):
/// drives that build and declares the produced library as the `[libStem]` code
/// asset. The CodeAsset `name` is the OS-independent lib stem (matching
/// `@Native(assetId: 'package:[pkg]/[libStem]')`), and the cmake target's output
/// name must be [libStem]. Cross-compiles via cmake's own toolchain vars derived
/// from the build config (NDK toolchain file / `CMAKE_SYSTEM_NAME=iOS` / OSX
/// arch); external deps are the plugin cmake's job. `NITRO_CMAKE_ARGS` (a
/// `;`-delimited env list) forwards extra configure args for prebuilt dep roots.
String buildExternalCmakeHookDart({
  required String libStem,
  required String pkg,
  String cmakeSrcDir = 'src',
}) {
  return '''
// GENERATED BY nitrogen — native-assets build hook (EXTERNAL cmake build).
import 'dart:io';

import 'package:code_assets/code_assets.dart';
import 'package:hooks/hooks.dart';

// Drives the plugin's own cmake project ($cmakeSrcDir/CMakeLists.txt) so an
// external C++ engine + deps link normally, then declares the built library as
// the `$libStem` code asset (name = OS-independent lib stem, matching
// @Native(assetId: 'package:$pkg/$libStem')).
void main(List<String> args) async {
  await build(args, (input, output) async {
    if (!input.config.buildCodeAssets) return;
    final code = input.config.code;
    final os = code.targetOS;
    final buildDir = Directory.fromUri(input.outputDirectory.resolve('cmake'))..createSync(recursive: true);
    final srcDir = input.packageRoot.resolve('$cmakeSrcDir').toFilePath();

    Future<void> cmake(List<String> a) async {
      final r = await Process.run('cmake', a, workingDirectory: buildDir.path);
      if (r.exitCode != 0) {
        throw Exception('cmake \${a.join(' ')} failed (\${r.exitCode}):\\n\${r.stdout}\\n\${r.stderr}');
      }
    }

    // Per-target cross-compile flags from the build config (external deps are
    // the plugin cmake's job — this only supplies the toolchain).
    final cross = <String>[];
    switch (os) {
      case OS.android:
        final tc = _androidToolchainFile(code.cCompiler?.compiler);
        if (tc == null) {
          throw Exception(
            'native-assets: Android cross-compile needs the NDK. Set ANDROID_NDK_HOME '
            '(or ANDROID_NDK / ANDROID_NDK_ROOT), or build via `flutter build` which '
            'provides the NDK compiler in the build config.',
          );
        }
        final abi = switch (code.targetArchitecture) {
          Architecture.arm64 => 'arm64-v8a',
          Architecture.arm => 'armeabi-v7a',
          Architecture.x64 => 'x86_64',
          Architecture.ia32 => 'x86',
          final a => throw Exception('native-assets: unsupported Android arch \$a'),
        };
        cross.addAll([
          '-DCMAKE_TOOLCHAIN_FILE=\${tc.toFilePath()}',
          '-DANDROID_ABI=\$abi',
          '-DANDROID_PLATFORM=android-\${code.android.targetNdkApi}',
        ]);
      case OS.iOS:
        final arch = switch (code.targetArchitecture) {
          Architecture.arm64 => 'arm64',
          Architecture.x64 => 'x86_64',
          final a => throw Exception('native-assets: unsupported iOS arch \$a'),
        };
        cross.addAll([
          '-DCMAKE_SYSTEM_NAME=iOS',
          '-DCMAKE_OSX_SYSROOT=\${code.iOS.targetSdk == IOSSdk.iPhoneSimulator ? 'iphonesimulator' : 'iphoneos'}',
          '-DCMAKE_OSX_ARCHITECTURES=\$arch',
          '-DCMAKE_OSX_DEPLOYMENT_TARGET=\${code.iOS.targetVersion}',
        ]);
      case OS.macOS:
        final arch = switch (code.targetArchitecture) {
          Architecture.arm64 => 'arm64',
          Architecture.x64 => 'x86_64',
          final a => throw Exception('native-assets: unsupported macOS arch \$a'),
        };
        cross.addAll([
          '-DCMAKE_OSX_ARCHITECTURES=\$arch',
          '-DCMAKE_OSX_DEPLOYMENT_TARGET=\${code.macOS.targetVersion}',
        ]);
      default:
        break; // Linux / Windows: native host build.
    }

    // NITRO_CMAKE_ARGS: extra configure args (`;`-delimited, so spaces survive)
    // for prebuilt dep roots. Spliced BEFORE `cross` so a user arg can't clobber
    // the generated toolchain/arch (cmake is last-wins on cache vars).
    final extra = (Platform.environment['NITRO_CMAKE_ARGS'] ?? '')
        .split(';')
        .where((s) => s.isNotEmpty)
        .toList();
    if (extra.isNotEmpty) stderr.writeln('native-assets: appending cmake args from NITRO_CMAKE_ARGS: \$extra');
    await cmake(['-S', srcDir, '-B', buildDir.path, '-DCMAKE_BUILD_TYPE=Release', ...extra, ...cross]);
    await cmake(['--build', buildDir.path, '--config', 'Release', '--parallel']);

    // Locate the produced shared library (cmake target output name == $libStem).
    final libFile = switch (os) {
      OS.windows => '$libStem.dll',
      OS.macOS || OS.iOS => 'lib$libStem.dylib',
      _ => 'lib$libStem.so',
    };
    final hits = buildDir
        .listSync(recursive: true)
        .whereType<File>()
        .where((f) => f.uri.pathSegments.last == libFile)
        .toList();
    if (hits.isEmpty) {
      throw Exception('native-assets: cmake produced no \$libFile under \${buildDir.path} '
          '(ensure the cmake target OUTPUT_NAME is "$libStem")');
    }

    output.assets.code.add(CodeAsset(
      package: '$pkg',
      name: '$libStem', // OS-independent — matches @Native assetId (Bug C)
      linkMode: DynamicLoadingBundled(),
      file: hits.first.uri,
    ));
    // Re-run this hook (→ cmake rebuild) whenever the generated bridge or any
    // src/ source changes — otherwise a regenerated bridge (new checksum) keeps
    // the cached dylib and the Dart<->native checksum guard fails at runtime.
    for (final dir in ['lib/src/generated/cpp', '$cmakeSrcDir']) {
      final d = Directory.fromUri(input.packageRoot.resolve('\$dir/'));
      if (d.existsSync()) {
        for (final f in d.listSync(recursive: true).whereType<File>()) {
          output.dependencies.add(f.uri);
        }
      }
    }
  });
}

// Locates the NDK's cmake toolchain file: first by walking up from the
// native-assets compiler path (.../toolchains/llvm/prebuilt/<host>/bin/clang →
// NDK root), else from the ANDROID_NDK* env vars. Null if the NDK isn't found.
Uri? _androidToolchainFile(Uri? compiler) {
  Uri? tcIn(Uri ndk) {
    final tc = ndk.resolve('build/cmake/android.toolchain.cmake');
    return File.fromUri(tc).existsSync() ? tc : null;
  }

  if (compiler != null) {
    var dir = compiler.resolve('.');
    for (var i = 0; i < 8; i++) {
      final tc = tcIn(dir);
      if (tc != null) return tc;
      final parent = dir.resolve('../');
      if (parent == dir) break;
      dir = parent;
    }
  }
  for (final v in const ['ANDROID_NDK_HOME', 'ANDROID_NDK', 'ANDROID_NDK_ROOT', 'ANDROID_NDK_LATEST_HOME']) {
    final e = Platform.environment[v];
    if (e != null && e.isNotEmpty) {
      final tc = tcIn(Directory(e).uri);
      if (tc != null) return tc;
    }
  }
  return null;
}
''';
}
