// Small #include forwarder file templates used by `nitrogen init` and
// `nitrogen link` to proxy source files into platform-specific build targets.
library;

// ── C++ source forwarders ──────────────────────────────────────────────────────

/// A CocoaPods-style `Classes/plugin.cpp` forwarder to `src/plugin.cpp`.
/// The relative path `../../src/` is correct from `{platform}/Classes/`.
String classesCppForwarder(String pluginName) => '#include "../../src/$pluginName.cpp"\n';

/// A CocoaPods-style `Classes/plugin.c` forwarder to `src/plugin.c`.
String classesCForwarder(String pluginName) => '#include "../../src/$pluginName.c"\n';

/// A `nitrogen link` managed C++ source forwarder — used in both CocoaPods
/// `Classes/` and SPM `Sources/<Plugin>Cpp/` targets.
///
/// [relativePath] is the relative path from the forwarder to the source file.
String managedCppForwarder(String relativePath) =>
    '// Generated by nitrogen link — do not edit.\n'
    '#include "$relativePath"\n';

/// A `nitrogen init` C++ source forwarder in an SPM Cpp target.
/// Points from `<platform>/<plugin>/Sources/<Plugin>Cpp/` up to `Classes/`.
String spmCppClassesForwarder(String pluginName) =>
    '// Generated by nitrogen init — do not edit.\n'
    '#include "../../../Classes/$pluginName.cpp"\n';

// ── Release/archive link anchors (CocoaPods) ──────────────────────────────────
//
// CocoaPods can build a plugin as a static library. The app's link then loads
// only the archive members something references, and nothing references the
// nitro bridges (looked up with dlsym) or the C++ impls (registered from a
// static constructor) — so a release/archive build drops them while debug
// keeps working. SwiftPM is unaffected: Xcode links each package target as one
// whole object file, not as archive members.

String _cIdent(String s) => s.replaceAll(RegExp(r'[^A-Za-z0-9_]'), '_');

/// The file `nitrogen link` writes into `<platform>/Classes/` to hold the
/// plugin's link anchors (see [appleLinkAnchorsTu]).
String appleLinkAnchorsFileName(String pluginName) => '$pluginName.link_anchors.g.mm';

/// The external symbol that marks one `Classes/Hybrid*.cpp` impl translation
/// unit. It carries the plugin name because in a statically linked app every
/// nitro plugin shares one symbol namespace.
String appleImplLinkAnchorSymbol(String pluginName, String implFileStem) => '${_cIdent(pluginName)}_nitro_link_anchor_${_cIdent(implFileStem)}';

/// Appended to a `Classes/Hybrid*.cpp` impl forwarder: an external symbol the
/// anchors file can reference, which pulls this translation unit — and the
/// auto-register constructor in it — into a static link.
String appleImplLinkAnchor(String symbol) =>
    '\n'
    '// nitrogen link anchor — do not edit. The plugin\'s *.link_anchors.g.mm\n'
    '// references this so a release/archive link keeps this translation unit and\n'
    '// the auto-register constructor in it. Not part of the plugin API.\n'
    'extern "C" __attribute__((used, visibility("default"))) void $symbol(void) {}\n';

/// The anchors translation unit: an Objective-C class whose method references
/// every bridge's `<lib>_init_dart_api_dl` ([initSymbols]) and every impl
/// anchor ([implAnchors]).
///
/// CocoaPods adds `-ObjC` to the app's link whenever a pod is static, and
/// `-ObjC` loads every archive member that defines an Objective-C class. So
/// this file is always loaded, and its references load the rest. It adds no
/// linker flag and reaches no target that does not already link the pod.
String appleLinkAnchorsTu({
  required String pluginName,
  required List<String> initSymbols,
  required List<String> implAnchors,
}) {
  final cls = 'NitroLinkAnchors_${_cIdent(pluginName)}';
  final b = StringBuffer()
    ..writeln('// Generated by nitrogen link — do not edit.')
    ..writeln('//')
    ..writeln('// Release/archive link anchors for $pluginName.')
    ..writeln('//')
    ..writeln('// When CocoaPods builds this pod as a static library, the app\'s link loads')
    ..writeln('// only the archive members something references. Nothing references the')
    ..writeln('// nitro bridges (looked up with dlsym) or the C++ implementations')
    ..writeln('// (registered from a static constructor), so a release/archive build drops')
    ..writeln('// them: the app works in debug and fails at launch from an archive.')
    ..writeln('//')
    ..writeln('// CocoaPods passes -ObjC whenever a pod is static, and -ObjC loads every')
    ..writeln('// archive member that defines an Objective-C class. This file defines one,')
    ..writeln('// so it is always loaded; the references below then load the bridges and')
    ..writeln('// implementations.')
    ..writeln('#import <Foundation/Foundation.h>')
    ..writeln('#include <stdint.h>')
    ..writeln()
    ..writeln('extern "C" {');
  for (final s in initSymbols) {
    b.writeln('intptr_t $s(void* data);');
  }
  for (final s in implAnchors) {
    b.writeln('void $s(void);');
  }
  b
    ..writeln('}')
    ..writeln()
    ..writeln('@interface $cls : NSObject')
    ..writeln('@end')
    ..writeln()
    ..writeln('@implementation $cls')
    ..writeln('+ (const void* const*)anchors {')
    ..writeln('  static const void* const kAnchors[] = {');
  for (final s in [...initSymbols, ...implAnchors]) {
    b.writeln('    (const void*)&$s,');
  }
  b
    ..writeln('  };')
    ..writeln('  return kAnchors;')
    ..writeln('}')
    ..writeln('@end');
  return b.toString();
}

// ── Obj-C++ bridge forwarders (.mm) ───────────────────────────────────────────

/// A `nitrogen link` managed `.mm` forwarder that wraps the generated C++
/// bridge so SPM compiles it as Obj-C++ and links the C ABI symbols.
///
/// [relativePath] is the relative path from the forwarder to `.bridge.g.cpp`.
String managedBridgeMmForwarder(String relativePath) =>
    '// Generated by nitrogen link — do not edit.\n'
    '#import <Foundation/Foundation.h>\n'
    '#include "$relativePath"\n';

/// A `nitrogen init` `.mm` forwarder for the SPM C++ target.
/// The 4-level relative path is fixed for the nested SPM layout:
///   `{platform}/{plugin}/Sources/{Plugin}Cpp/` → `lib/src/generated/cpp/`
String spmBridgeMmForwarder(String pluginName) =>
    '// Generated by nitrogen init — do not edit.\n'
    '// Updated with resolved paths by nitrogen link.\n'
    '#import <Foundation/Foundation.h>\n'
    '#include "../../../../lib/src/generated/cpp/$pluginName.bridge.g.cpp"\n';

// ── dart_api_dl.c forwarders ───────────────────────────────────────────────────

/// `dart_api_dl.c` forwarder for CocoaPods `Classes/` targets.
/// Must be a `.c` file (not `.cpp`) so the void*/function-pointer casts
/// inside `dart_api_dl.c` are accepted without C++ complaints.
const String classesDartApiDlForwarder = '#include "../../src/dart_api_dl.c"\n';

/// `dart_api_dl.c` forwarder for CocoaPods ios/macos `Classes/` targets with
/// the comment explaining why it must remain `.c`.
const String classesIosDartApiDlForwarder =
    '// Forwarder — compiled by CocoaPods/SPM so the Dart DL API is\n'
    '// available in the dylib. Kept as .c so it compiles as C, not C++.\n'
    '#include "../../src/dart_api_dl.c"\n';

const String classesMacosDartApiDlForwarder =
    '// Forwarder — compiled as C so it can be used in the dylib.\n'
    '#include "../../src/dart_api_dl.c"\n';
