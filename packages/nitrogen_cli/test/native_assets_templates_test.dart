import 'dart:io';

import 'package:nitrogen_cli/commands/link_command.dart';
import 'package:nitrogen_cli/templates/native_assets_templates.dart';
import 'package:path/path.dart' as p;
import 'package:test/test.dart';

void main() {
  group('native-assets build-hook template (perf lever 1 / v0.8.0)', () {
    final hook = buildHookDart(
      modules: [
        (libStem: 'my_cpp', cppSources: ['lib/src/generated/cpp/my_cpp.bridge.g.cpp', 'src/HybridMyCpp.cpp']),
      ],
    );

    test('is a valid build() hook using CBuilder for the code asset', () {
      expect(hook, contains("import 'package:hooks/hooks.dart';"));
      expect(hook, contains("import 'package:native_toolchain_c/native_toolchain_c.dart';"));
      expect(hook, contains('await build(args, (input, output) async {'));
      expect(hook, contains('CBuilder.library('));
      expect(hook, contains("name: 'my_cpp'"));
      expect(hook, contains("assetName: 'my_cpp'"));
      expect(hook, contains('language: Language.cpp'));
      expect(hook, contains("std: 'c++17'"));
      expect(hook, contains('.run('));
    });

    test('compiles the bridge + impl + vendored dart_api_dl.c, includes vendor dir', () {
      expect(hook, contains("'lib/src/generated/cpp/my_cpp.bridge.g.cpp',"));
      expect(hook, contains("'src/HybridMyCpp.cpp',"));
      expect(hook, contains("'src/nitro_native/dart_api_dl.c',"));
      expect(hook, contains("includes: ['src/nitro_native', 'lib/src/generated/cpp']"));
    });

    test('uses the ROOT logger (named logger + .level throws without hierarchicalLogging)', () {
      expect(hook, contains("Logger('')"));
      expect(hook, isNot(contains("Logger('my_cpp')")));
    });

    test('links libc++ statically on Android (self-contained .so)', () {
      expect(hook, contains('input.config.code.targetOS == OS.android'));
      expect(hook, contains("cppLinkStdLib: android ? 'c++_static' : null"));
    });

    test('declares the build-time hook deps (regular deps, not dev)', () {
      expect(nativeAssetsHookDeps.keys, containsAll(['hooks', 'code_assets', 'native_toolchain_c', 'logging']));
      expect(nativeAssetsHookDeps['native_toolchain_c'], '^0.19.5');
    });

    test('is marked generated / do-not-edit', () => expect(hook, contains('GENERATED BY nitrogen')));

    test('multi-module → one CBuilder.library per module, shared vendored DL API', () {
      final multi = buildHookDart(modules: [
        (libStem: 'alpha', cppSources: ['lib/src/generated/cpp/alpha.bridge.g.cpp', 'src/HybridAlpha.cpp']),
        (libStem: 'beta', cppSources: ['lib/src/generated/cpp/beta.bridge.g.cpp', 'src/HybridBeta.cpp']),
      ]);
      expect('CBuilder.library('.allMatches(multi).length, 2);
      expect(multi, contains("assetName: 'alpha'"));
      expect(multi, contains("assetName: 'beta'"));
      // distinct asset names → distinct dylibs (no libcalc.dylib-style clash)
      expect(multi, contains("'src/HybridAlpha.cpp',"));
      expect(multi, contains("'src/HybridBeta.cpp',"));
      // the vendored DL API is compiled into each
      expect("'src/nitro_native/dart_api_dl.c',".allMatches(multi).length, 2);
    });
  });

  group('linkNativeAssetsHook (CLI build-system wiring)', () {
    late Directory plugin;
    late Directory fakeNitroNative;

    setUp(() {
      plugin = Directory.systemTemp.createTempSync('na_plugin');
      // generated bridge the hook compiles
      Directory(p.join(plugin.path, 'lib', 'src', 'generated', 'cpp')).createSync(recursive: true);
      File(p.join(plugin.path, 'lib', 'src', 'generated', 'cpp', 'calc.bridge.g.cpp')).writeAsStringSync('// bridge');
      // the user's impl
      Directory(p.join(plugin.path, 'src')).createSync(recursive: true);
      File(p.join(plugin.path, 'src', 'HybridCalc.cpp')).writeAsStringSync('// impl');
      File(p.join(plugin.path, 'pubspec.yaml')).writeAsStringSync('name: calc\ndependencies:\n  flutter:\n    sdk: flutter\n');
      // a fake nitro src/native to vendor from
      fakeNitroNative = Directory(p.join(plugin.path, '_nitro', 'src', 'native'))..createSync(recursive: true);
      for (final n in [...nativeAssetsVendoredCSources, ...nativeAssetsVendoredHeaders]) {
        File(p.join(fakeNitroNative.path, n)).writeAsStringSync('// $n');
      }
      Directory(p.join(fakeNitroNative.path, 'internal')).createSync();
      File(p.join(fakeNitroNative.path, 'internal', 'dart_api_dl_impl.h')).writeAsStringSync('// impl.h');
    });
    tearDown(() => plugin.deleteSync(recursive: true));

    test('writes hook, vendors nitro C runtime, injects pubspec deps', () {
      linkNativeAssetsHook(
        [ModuleInfo(lib: 'calc', module: 'Calc', isCpp: true)],
        fakeNitroNative.path,
        baseDir: plugin.path,
      );
      // hook written, compiling the real bridge + impl
      final hook = File(p.join(plugin.path, 'hook', 'build.dart'));
      expect(hook.existsSync(), isTrue);
      expect(hook.readAsStringSync(), contains("assetName: 'calc'"));
      expect(hook.readAsStringSync(), contains('lib/src/generated/cpp/calc.bridge.g.cpp'));
      expect(hook.readAsStringSync(), contains('src/HybridCalc.cpp'));
      // nitro C runtime vendored (incl. internal/)
      expect(File(p.join(plugin.path, 'src', 'nitro_native', 'dart_api_dl.c')).existsSync(), isTrue);
      expect(File(p.join(plugin.path, 'src', 'nitro_native', 'nitro_completion_batch.h')).existsSync(), isTrue);
      expect(File(p.join(plugin.path, 'src', 'nitro_native', 'internal', 'dart_api_dl_impl.h')).existsSync(), isTrue);
      // pubspec deps injected under dependencies:
      final pub = File(p.join(plugin.path, 'pubspec.yaml')).readAsStringSync();
      for (final k in nativeAssetsHookDeps.keys) {
        expect(pub, contains('  $k:'), reason: 'missing hook dep $k');
      }
    });

    test('pubspec injection is idempotent', () {
      final pubspec = p.join(plugin.path, 'pubspec.yaml');
      expect(injectNativeAssetsPubspecDeps(pubspec), isTrue);
      expect(injectNativeAssetsPubspecDeps(pubspec), isFalse, reason: 'second run is a no-op');
    });

    test('no C++ module → no-op (hook not written)', () {
      linkNativeAssetsHook(
        [ModuleInfo(lib: 'calc', module: 'Calc', isCpp: false)],
        fakeNitroNative.path,
        baseDir: plugin.path,
      );
      expect(File(p.join(plugin.path, 'hook', 'build.dart')).existsSync(), isFalse);
    });
  });
}
