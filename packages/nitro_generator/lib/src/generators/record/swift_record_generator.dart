String _generateSwiftRecords(BridgeSpec spec, {bool emitBoilerplate = true}) {
  // NativeImpl.cpp bridge files use emitBoilerplate:false — shared library types
  // (NitroNullableInt, NitroOptInt64, etc.) are provided by the non-cpp bridge in
  // the same Swift module. Skip them here to avoid "invalid redeclaration" errors.
  final localRecords = emitBoilerplate ? spec.nativeRecordTypes : spec.nativeRecordTypes.where((r) => !_nitroLibraryRecordTypes.contains(r.name)).toList();

  // ── fromReader/writeFields extensions for plain structs embedded in records ──
  // The Dart side generates RecordExt for HybridStructs; we mirror this for Swift.
  // Without these extensions, `LiveTrackingUpdate.fromReader` cannot call
  // `PackageDimensions.fromReader(r)` because plain structs have no such method.
  final structMap = {for (final st in spec.structs) st.name: st};
  final enumNames = spec.enums.map((e) => e.name).toSet();
  final structNames = spec.structs.map((st) => st.name).toSet();

  final referencedStructs = spec.structsNeedingByteCodec(localRecords);

  // Variants use NitroRecordReader/Writer for their binary payload, even when
  // there are no @HybridRecord declarations in the file.
  final needsBoilerplateForVariants = emitBoilerplate && spec.localVariants.isNotEmpty;
  // So does the map codec: a module whose only bridged containers are maps
  // still needs the reader and writer.
  final needsBoilerplateForMaps =
      emitBoilerplate && (spec.functions.any((f) => f.returnType.isMap || f.params.any((p) => p.type.isMap)) || spec.properties.any((p) => p.type.isMap));
  // Early exit only when there is truly nothing to generate.
  if (localRecords.isEmpty && referencedStructs.isEmpty && !needsBoilerplateForVariants && !needsBoilerplateForMaps) return '';

  final s = CodeWriter();
  s.writeln('// --- @HybridRecord binary extensions (generated by Nitrogen) ---');
  s.writeln();

  for (final stName in referencedStructs) {
    final st = structMap[stName]!;
    s.writeln('extension ${st.name} {');

    s.writeln('  public static func fromReader(_ r: NitroRecordReader) -> ${st.name} {');
    s.writeln('    return ${st.name}(');
    // Comma as a JOINER, never a per-argument suffix: a trailing comma in an
    // argument list is Swift 6.1+ syntax (SE-0439) and fails to parse on
    // Xcode <= 16.2 toolchains (issue #22).
    s.writeln(st.fields.map((f) => '      ${f.name}: ${_swiftStructReadExpr(f, enumNames, structNames)}').join(',\n'));
    s.writeln('    )');
    s.writeln('  }');
    s.writeln();

    s.writeln('  public func writeFields(_ writer: NitroRecordWriter) {');
    for (final f in st.fields) {
      _swiftStructWriteStmt(s, f, enumNames, structNames, st);
    }
    s.writeln('  }');
    s.writeln('}');
    s.writeln();
  }

  for (final rt in localRecords) {
    s.writeln('public struct ${rt.name}: NitroEncodable {');
    for (final f in rt.fields) {
      final opt = f.isNullable ? '?' : '';
      s.writeln('  public var ${f.name}: ${_swiftType(f)}$opt');
    }
    s.writeln();

    final params = rt.fields.map((f) => '${f.name}: ${_swiftType(f)}${f.isNullable ? '?' : ''}').join(', ');
    s.writeln('  public init($params) {');
    for (final f in rt.fields) {
      s.writeln('    self.${f.name} = ${f.name}');
    }
    s.writeln('  }');
    s.writeln();

    s.writeln('  public static func fromNative(_ ptr: UnsafeMutablePointer<UInt8>) -> ${rt.name} {');
    s.writeln('    return fromReader(NitroRecordReader(ptr: ptr))');
    s.writeln('  }');
    s.writeln();

    s.writeln('  public static func fromReader(_ r: NitroRecordReader) -> ${rt.name} {');
    s.writeln('    return ${rt.name}(');
    // Joiner, not suffix — trailing commas in argument lists are Swift 6.1+
    // only (SE-0439); Xcode <= 16.2 fails with "Unexpected ',' separator"
    // (issue #22).
    s.writeln(rt.fields.map((f) => '      ${f.name}: ${_swiftRead(f)}').join(',\n'));
    s.writeln('    )');
    s.writeln('  }');
    s.writeln();

    s.writeln('  public func writeFields(_ writer: NitroRecordWriter) {');
    for (final f in rt.fields) {
      _swiftWriteStmt(s, f);
    }
    s.writeln('  }');
    s.writeln();

    s.writeln('  public func toNative() -> UnsafeMutablePointer<UInt8>? {');
    s.writeln('    let writer = NitroRecordWriter()');
    s.writeln('    writeFields(writer)');
    s.writeln('    return writer.toNative()');
    s.writeln('  }');
    // ── Built-in NitroNullable types: add nullable computed var + fromNullable factory ──
    switch (rt.name) {
      case 'NitroNullableInt':
        s.writeln('  public var nullable: Int64? { hasValue ? value : nil }');
        s.writeln('  public static func fromNullable(_ v: Int64?) -> NitroNullableInt {');
        s.writeln('    return NitroNullableInt(hasValue: v != nil, value: v ?? 0)');
        s.writeln('  }');
      case 'NitroNullableDouble':
        s.writeln('  public var nullable: Double? { hasValue ? value : nil }');
        s.writeln('  public static func fromNullable(_ v: Double?) -> NitroNullableDouble {');
        s.writeln('    return NitroNullableDouble(hasValue: v != nil, value: v ?? 0.0)');
        s.writeln('  }');
      case 'NitroNullableBool':
        s.writeln('  public var nullable: Bool? { hasValue ? value : nil }');
        s.writeln('  public static func fromNullable(_ v: Bool?) -> NitroNullableBool {');
        s.writeln('    return NitroNullableBool(hasValue: v != nil, value: v ?? false)');
        s.writeln('  }');
    }
    s.writeln('}');
    s.writeln();
  }

  if (emitBoilerplate) {
    s.writeln(_swiftRecordWriterReader);
  }
  return s.toString();
}

String _swiftType(BridgeRecordField f) {
  switch (f.kind) {
    case RecordFieldKind.primitive:
      return _swiftBase(f.dartType);
    case RecordFieldKind.enumValue:
      return bareTypeName(f.dartType);
    case RecordFieldKind.recordObject:
      return bareTypeName(f.dartType);
    case RecordFieldKind.listPrimitive:
      return '[${_swiftBase(f.itemTypeName ?? 'Any')}]';
    case RecordFieldKind.listEnumValue:
      return '[${f.itemTypeName}]';
    case RecordFieldKind.listRecordObject:
      return '[${f.itemTypeName}]';
    case RecordFieldKind.typedData:
      return _swiftTypedDataType(bareTypeName(f.dartType));
    case RecordFieldKind.struct:
      return bareTypeName(f.dartType);
  }
}

String _swiftTypedDataType(String dartType) {
  switch (dartType) {
    case 'Uint8List':
    case 'Int8List':
      return 'Data';
    case 'Int16List':
    case 'Uint16List':
      return '[Int16]';
    case 'Int32List':
    case 'Uint32List':
      return '[Int32]';
    case 'Int64List':
    case 'Uint64List':
      return '[Int64]';
    case 'Float32List':
      return '[Float]';
    case 'Float64List':
      return '[Double]';
    default:
      return 'Data';
  }
}

String _swiftBase(String dartType) {
  final base = bareTypeName(dartType);
  switch (base) {
    case 'int':
      return 'Int64';
    case 'double':
      return 'Double';
    case 'bool':
      return 'Bool';
    case 'String':
      return 'String';
    default:
      return 'Int64';
  }
}

/// Wraps a list field's read in the null tag when the field is nullable.
String _swiftListRead(BridgeRecordField f, String read) => f.isNullable ? 'r.readNullTag() ? nil : $read' : read;

/// Writer counterpart to [_swiftListRead].
void _swiftWriteListField(CodeWriter s, BridgeRecordField f, void Function(String accessor) body) {
  if (!f.isNullable) {
    body(f.name);
    return;
  }
  s.writeln('    writer.writeNullTag(${f.name} == nil)');
  s.writeln('    if let _list = ${f.name} {');
  body('_list');
  s.writeln('    }');
}

String _swiftReadCall(String base) {
  switch (base) {
    case 'int':
      return 'r.readInt()';
    case 'double':
      return 'r.readDouble()';
    case 'bool':
      return 'r.readBool()';
    case 'String':
      return 'r.readString()';
    case 'Uint8List':
      return 'r.readBlob()';
    default:
      return 'r.readInt()';
  }
}

String _swiftRead(BridgeRecordField f) {
  switch (f.kind) {
    case RecordFieldKind.primitive:
      final base = bareTypeName(f.dartType);
      if (f.isNullable) return 'r.readNullTag() ? nil : ${_swiftReadCall(base)}';
      return _swiftReadCall(base);
    case RecordFieldKind.enumValue:
      final base = bareTypeName(f.dartType);
      final read = '$base(rawValue: r.readInt())!';
      if (f.isNullable) return 'r.readNullTag() ? nil : $read';
      return read;
    case RecordFieldKind.recordObject:
      final base = bareTypeName(f.dartType);
      if (f.isNullable) return 'r.readNullTag() ? nil : $base.fromReader(r)';
      return '$base.fromReader(r)';
    // Nullable list fields carry a null tag like every other nullable field —
    // an absent list and an empty list are distinct values.
    case RecordFieldKind.listPrimitive:
      final item = f.itemTypeName ?? 'int';
      // [Int64] / [Double] storage is the wire form: one copy for the list.
      final bulk = const {'int': 'r.readIntList()', 'double': 'r.readDoubleList()', 'bool': 'r.readBoolList()'}[item];
      return _swiftListRead(f, bulk ?? '(0..<Int(r.readInt32())).map { _ in ${_swiftReadCall(item)} }');
    case RecordFieldKind.listEnumValue:
      final item = f.itemTypeName!;
      return _swiftListRead(f, '(0..<Int(r.readInt32())).map { _ in $item(rawValue: r.readInt())! }');
    case RecordFieldKind.listRecordObject:
      final item = f.itemTypeName!;
      return _swiftListRead(f, '(0..<Int(r.readInt32())).map { _ in $item.fromReader(r) }');
    case RecordFieldKind.typedData:
      final base = bareTypeName(f.dartType);
      final read = _swiftTypedDataRead(base);
      if (f.isNullable) return 'r.readNullTag() ? nil : $read';
      return read;
    case RecordFieldKind.struct:
      final base = bareTypeName(f.dartType);
      if (f.isNullable) return 'r.readNullTag() ? nil : $base.fromReader(r)';
      return '$base.fromReader(r)';
  }
}

String _swiftTypedDataRead(String dartType) {
  // Wider arrays are copied once, straight into the array's storage; going
  // through Data and then Array(...) copied the bytes twice.
  switch (dartType) {
    case 'Int16List':
    case 'Uint16List':
      return 'r.readArray(of: Int16.self)';
    case 'Int32List':
    case 'Uint32List':
      return 'r.readArray(of: Int32.self)';
    case 'Int64List':
    case 'Uint64List':
      return 'r.readArray(of: Int64.self)';
    case 'Float32List':
      return 'r.readArray(of: Float.self)';
    case 'Float64List':
      return 'r.readArray(of: Double.self)';
    default: // Uint8List, Int8List
      return 'r.readBlob()';
  }
}

void _swiftWriteStmt(CodeWriter s, BridgeRecordField f) {
  switch (f.kind) {
    case RecordFieldKind.primitive:
      final base = bareTypeName(f.dartType);
      if (f.isNullable) {
        s.writeln('    writer.writeNullTag(${f.name} == nil)');
        s.writeln('    if let val = ${f.name} { writer.${_swiftWriterCall(base, 'val')} }');
      } else {
        s.writeln('    writer.${_swiftWriterCall(base, f.name)}');
      }
      break;
    case RecordFieldKind.enumValue:
      if (f.isNullable) {
        s.writeln('    writer.writeNullTag(${f.name} == nil)');
        s.writeln('    if let val = ${f.name} { writer.writeInt(val.rawValue) }');
      } else {
        s.writeln('    writer.writeInt(${f.name}.rawValue)');
      }
      break;
    case RecordFieldKind.recordObject:
      if (f.isNullable) {
        s.writeln('    writer.writeNullTag(${f.name} == nil)');
        s.writeln('    if let val = ${f.name} { val.writeFields(writer) }');
      } else {
        s.writeln('    ${f.name}.writeFields(writer)');
      }
      break;
    case RecordFieldKind.listPrimitive:
      final item = f.itemTypeName ?? 'int';
      final bulk = const {'int': 'writeIntList', 'double': 'writeDoubleList', 'bool': 'writeBoolList'}[item];
      _swiftWriteListField(s, f, (a) {
        if (bulk != null) {
          s.writeln('    writer.$bulk($a)');
          return;
        }
        s.writeln('    writer.writeInt32(Int32($a.count))');
        s.writeln('    for e in $a { writer.${_swiftWriterCall(item, 'e')} }');
      });
      break;
    case RecordFieldKind.listEnumValue:
      _swiftWriteListField(s, f, (a) {
        s.writeln('    writer.writeInt32(Int32($a.count))');
        s.writeln('    for e in $a { writer.writeInt(e.rawValue) }');
      });
      break;
    case RecordFieldKind.listRecordObject:
      _swiftWriteListField(s, f, (a) {
        s.writeln('    writer.writeInt32(Int32($a.count))');
        s.writeln('    for e in $a { e.writeFields(writer) }');
      });
      break;
    case RecordFieldKind.typedData:
      final base = bareTypeName(f.dartType);
      if (f.isNullable) {
        s.writeln('    writer.writeNullTag(${f.name} == nil)');
        s.writeln('    if let val = ${f.name} { ${_swiftTypedDataWrite(base, 'val', 'writer')} }');
      } else {
        s.writeln('    ${_swiftTypedDataWrite(base, f.name, 'writer')}');
      }
      break;
    case RecordFieldKind.struct:
      // @HybridStruct embedded inline — write via writeFields.
      if (f.isNullable) {
        s.writeln('    writer.writeNullTag(${f.name} == nil)');
        s.writeln('    if let val = ${f.name} { val.writeFields(writer) }');
      } else {
        s.writeln('    ${f.name}.writeFields(writer)');
      }
      break;
  }
}

String _swiftTypedDataWrite(String dartType, String expr, String writer) {
  switch (dartType) {
    case 'Uint8List':
    case 'Int8List':
      return '$writer.writeBlob($expr)';
    default: // wider arrays: the array's bytes, once (was Data(buffer:) + Array(...))
      return '$expr.withUnsafeBytes { $writer.writeRaw(\$0) }';
  }
}

String _swiftWriterCall(String base, String expr) {
  switch (base) {
    case 'int':
      return 'writeInt($expr)';
    case 'double':
      return 'writeDouble($expr)';
    case 'bool':
      return 'writeBool($expr)';
    case 'String':
      return 'writeString($expr)';
    case 'Uint8List':
      return 'writeBlob($expr)';
    default:
      return 'writeInt($expr)';
  }
}

String _swiftStructReadExpr(BridgeField f, Set<String> enumNames, Set<String> structNames) {
  final base = bareTypeName(f.type.name);
  if (enumNames.contains(base)) return '$base(rawValue: Int(r.readInt()))!';
  if (structNames.contains(base)) return '$base.fromReader(r)';
  if (base == 'Uint8List' && f.zeroCopy) {
    return 'r.readBlobAsPointer()';
  }
  return _swiftReadCall(base);
}

void _swiftStructWriteStmt(CodeWriter s, BridgeField f, Set<String> enumNames, Set<String> structNames, BridgeStruct st) {
  final base = bareTypeName(f.type.name);
  if (enumNames.contains(base)) {
    s.writeln('    writer.writeInt(Int64(${f.name}.rawValue))');
  } else if (structNames.contains(base)) {
    s.writeln('    ${f.name}.writeFields(writer)');
  } else {
    if (base == 'Uint8List' && f.zeroCopy) {
      final countField = st.fields.firstWhere(
        (cf) => ['stride', 'length', 'size', 'count'].contains(cf.name),
        orElse: () => st.fields.first,
      );
      final countExpr = 'Int(${countField.name})';
      s.writeln('    if let ptr = ${f.name} {');
      s.writeln('        writer.writeBlob(Data(bytes: ptr, count: $countExpr))');
      s.writeln('    } else {');
      s.writeln('        writer.writeInt32(0)');
      s.writeln('    }');
    } else {
      s.writeln('    writer.${_swiftWriterCall(base, f.name)}');
    }
  }
}

const _swiftRecordWriterReader = '''
public class NitroRecordWriter {
  // One malloc'd block laid out as [4B length][payload]: toNative() hands it to
  // Dart as it is, with no second allocation and no copy. (It was a [UInt8]
  // copied into a fresh block per record.)
  private var block: UnsafeMutablePointer<UInt8>?
  private var count = 0
  private var capacity = 0
  public init() {}
  deinit { free(block) }
  /// Room for [n] more payload bytes; returns where they go.
  private func room(_ n: Int) -> UnsafeMutablePointer<UInt8> {
      if block == nil || count + n > capacity {
          capacity = max(capacity * 2, count + n, 252)
          block = realloc(block, 4 + capacity)!.assumingMemoryBound(to: UInt8.self)
      }
      let at = block! + 4 + count
      count += n
      return at
  }
  private func put(_ from: UnsafeRawBufferPointer) {
      if from.count > 0 { memcpy(room(from.count), from.baseAddress!, from.count) }
  }
  /// The payload written so far, as a copy (no length prefix).
  public var bytes: [UInt8] {
      guard let block = block else { return [] }
      return Array(UnsafeBufferPointer(start: block + 4, count: count))
  }
  public func writeInt(_ v: Int64) {
      var val = v.littleEndian
      memcpy(room(8), &val, 8)
  }
  public func writeInt32(_ v: Int32) {
      var val = v.littleEndian
      memcpy(room(4), &val, 4)
  }
  public func writeDouble(_ v: Double) {
      var val = v.bitPattern.littleEndian
      memcpy(room(8), &val, 8)
  }
  public func writeBool(_ v: Bool) {
      room(1).pointee = v ? 1 : 0
  }
  public func writeByte(_ v: UInt8) {
      room(1).pointee = v
  }
  /// `[4B bodyLen + 4][4B bodyLen][body]`: a record or variant as a map value,
  /// framed the way Dart reads it back.
  public func writeFramed(_ body: (NitroRecordWriter) -> Void) {
      let at = count
      _ = room(8)
      body(self)
      var inner = Int32(count - at - 8).littleEndian
      var outer = Int32(count - at - 4).littleEndian
      memcpy(block! + 4 + at, &outer, 4)
      memcpy(block! + 4 + at + 4, &inner, 4)
  }
  public func writeString(_ v: String) {
      var s = v
      s.withUTF8 { utf8 in
          writeInt32(Int32(utf8.count))
          put(UnsafeRawBufferPointer(utf8))
      }
  }
  public func writeNullTag(_ isNull: Bool) {
      room(1).pointee = isNull ? 0 : 1
  }
  public func writeBlob(_ v: Data) {
      writeInt32(Int32(v.count))
      v.withUnsafeBytes { put(\$0) }
  }
  /// Raw bytes behind a 4-byte byte count: one copy, for typed arrays.
  public func writeRaw(_ raw: UnsafeRawBufferPointer) {
      writeInt32(Int32(raw.count))
      put(raw)
  }
  /// `[4B count][8B x n]`. The array's storage is the wire form (little-endian
  /// on every Apple target), so the whole list is one copy.
  public func writeIntList(_ v: [Int64]) {
      writeInt32(Int32(v.count))
      v.withUnsafeBytes { put(\$0) }
  }
  public func writeDoubleList(_ v: [Double]) {
      writeInt32(Int32(v.count))
      v.withUnsafeBytes { put(\$0) }
  }
  /// `[4B count][1B x n]`: a Bool is stored as the byte 0 or 1, the wire form.
  public func writeBoolList(_ v: [Bool]) {
      writeInt32(Int32(v.count))
      v.withUnsafeBytes { put(\$0) }
  }
  /// The finished record, `[4B length][payload]`, for Dart to free. Gives up
  /// this writer's block: the writer is empty afterwards.
  public func toNative() -> UnsafeMutablePointer<UInt8>? {
      _ = room(0)
      var length = Int32(count).littleEndian
      memcpy(block!, &length, 4)
      let out = block
      block = nil
      count = 0
      capacity = 0
      return out
  }
  public static func encodeList<T>(_ items: [T], writeItem: (NitroRecordWriter, T) -> Void) -> UnsafeMutablePointer<UInt8>? {
      let w = NitroRecordWriter()
      w.writeInt32(Int32(items.count))
      for item in items { writeItem(w, item) }
      return w.toNative()
  }
  /// Encodes a list of nullable items.
  /// Wire format: [4B count][for each: 1B hasValue][item bytes (only if hasValue)]
  /// Counterpart: NitroRecordReader.decodeNullableList / Dart RecordReader.decodeNullableList.
  public static func encodeNullableList<T>(_ items: [T?], writeItem: (NitroRecordWriter, T) -> Void) -> UnsafeMutablePointer<UInt8>? {
      let w = NitroRecordWriter()
      w.writeInt32(Int32(items.count))
      for item in items {
          w.writeBool(item != nil)
          if let v = item { writeItem(w, v) }
      }
      return w.toNative()
  }
  /// Encodes a list with a per-item byte-offset table for O(1) random access.
  /// Wire format (payload after outer 4B length prefix):
  ///   [int32 count][int64 × count offsets from payload start][item bytes...]
  /// Counterpart: Dart LazyRecordList.decode / RecordWriter.encodeIndexedList.
  public static func encodeIndexedList<T>(_ items: [T], writeItem: (NitroRecordWriter, T) -> Void) -> UnsafeMutablePointer<UInt8>? {
      // One writer: reserve the offset table, write each item straight after
      // it, then fill the table in. (It was a writer and a byte array per item.)
      let w = NitroRecordWriter()
      w.writeInt32(Int32(items.count))
      _ = w.room(8 * items.count)
      for (i, item) in items.enumerated() {
          var offset = Int64(w.count).littleEndian
          memcpy(w.block! + 4 + 4 + 8 * i, &offset, 8)
          writeItem(w, item)
      }
      return w.toNative()
  }
}

public class NitroRecordReader {
  public let bytes: UnsafeMutablePointer<UInt8>
  public var pos: Int = 0
  public init(ptr: UnsafeMutablePointer<UInt8>) {
      self.bytes = ptr.advanced(by: 4)
  }
  public init(payload: UnsafeMutablePointer<UInt8>) {
      self.bytes = payload
  }
  public func readInt() -> Int64 {
      var v: Int64 = 0
      _ = memcpy(&v, bytes.advanced(by: pos), 8)
      pos += 8
      return Int64(littleEndian: v)
  }
  public func readInt32() -> Int32 {
      var v: Int32 = 0
      _ = memcpy(&v, bytes.advanced(by: pos), 4)
      pos += 4
      return Int32(littleEndian: v)
  }
  public func readDouble() -> Double {
      var v: UInt64 = 0
      _ = memcpy(&v, bytes.advanced(by: pos), 8)
      pos += 8
      return Double(bitPattern: UInt64(littleEndian: v))
  }
  public func readBool() -> Bool {
      let v = bytes[pos]
      pos += 1
      return v != 0
  }
  public func readString() -> String {
      let len = Int(readInt32())
      guard len > 0 else { return "" }
      // The standard library's decoder, not Foundation's String(bytes:encoding:):
      // several times faster on short strings (measured), and Dart only sends
      // valid UTF-8.
      let s = String(decoding: UnsafeBufferPointer(start: bytes.advanced(by: pos), count: len), as: UTF8.self)
      pos += len
      return s
  }
  public func readNullTag() -> Bool {
      let v = bytes[pos]
      pos += 1
      return v == 0
  }
  public func readBlob() -> Data {
      let len = Int(readInt32())
      let data = Data(bytes: bytes.advanced(by: pos), count: len)
      pos += len
      return data
  }
  /// [n] fixed-size values copied once into a new array's storage.
  private func readValues<T>(_ n: Int, of type: T.Type) -> [T] {
      let byteCount = n * MemoryLayout<T>.stride
      let out = [T](unsafeUninitializedCapacity: n) { buffer, count in
          if n > 0 { memcpy(buffer.baseAddress!, bytes.advanced(by: pos), byteCount) }
          count = n
      }
      pos += byteCount
      return out
  }
  /// A typed array field: `[4B byteCount][bytes]`.
  public func readArray<T>(of type: T.Type) -> [T] {
